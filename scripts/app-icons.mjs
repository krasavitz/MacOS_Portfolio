/* Generates the app icons in public/images/app-icons/.

   Style: iPod nano colours. Each app is a tile of anodized aluminium in one
   of the iPod colourways — a satin top-to-bottom sheen and a fine brushed
   grain — with a solid, rounded white glyph pressed into it (a soft dark
   copy just below reads as engraving). Holes in a glyph (the chat dots, the
   resume lines) are real cut-outs, so the metal shows through.

   It also writes one folder per iPod colour (folder-<colour>.svg) for the
   project folders in the Finder; FOLDERS maps each project to its colour,
   and constants/index.js points each folder's `icon` at the result.

   To change one, edit its colours or glyph below and run:
     node scripts/app-icons.mjs
   Glyphs are drawn in the icon's own 128×128 space and scaled down to sit
   inside the tile: `shape` is the solid glyph (corners rounded for you),
   `holes` is cut out of it. */

