const out = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "public", "images", "app-icons");
fs.mkdirSync(out, { recursive: true });
for (const [name, icon] of Object.entries(ICONS)) fs.writeFileSync(path.join(out, `${name}.svg`), svgFor(name, icon));
for (const [colour, metal] of Object.entries(FOLDER_COLOURS))
    fs.writeFileSync(path.join(out, `folder-${colour}.svg`), folderSvg(colour, metal));
console.log(`wrote ${Object.keys(ICONS).length} icons and ${Object.keys(FOLDER_COLOURS).length} folders to public/images/app-icons/`);
